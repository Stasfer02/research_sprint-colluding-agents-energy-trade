"""Snapshot OpenRouter models into configs/models_openrouter.yaml (prices, capabilities, pinned provider).

    python scripts/openrouter_models.py meta-llama/llama-3.3-70b-instruct qwen/qwen3.8-flash ... [--out FILE]

For each model, picks the cheapest live provider endpoint (status ok, uptime >= 99%, context >= 32k) that
supports `seed` (and `temperature` if the model does), and pins it. Experiments then route every call to
that provider with fallbacks disabled, so a model's outputs never silently switch provider (or quantization)
mid-experiment. Uses only public endpoints (no key needed). The file is committed for traceability.
"""

from __future__ import annotations

import argparse
import datetime
import json
import sys
import urllib.request
from pathlib import Path

import yaml

API = "https://openrouter.ai/api/v1"
MIN_CONTEXT = 32_000


def get(path: str) -> dict:
    req = urllib.request.Request(f"{API}{path}", headers={"User-Agent": "colluding-desks-research"})
    return json.load(urllib.request.urlopen(req, timeout=30))["data"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("models", nargs="+")
    ap.add_argument("--out", default="configs/models_openrouter.yaml")
    args = ap.parse_args()
    out = Path(args.out)
    registry = yaml.safe_load(out.read_text()) if out.exists() else {}
    registry = registry or {}
    catalog = {m["id"]: m for m in get("/models")}
    for mid in args.models:
        if mid not in catalog:
            print(f"!! {mid}: not in catalog")
            continue
        model_params = set(catalog[mid].get("supported_parameters") or [])
        wants_temp = "temperature" in model_params
        eps = get(f"/models/{mid}/endpoints")["endpoints"]
        ok = []
        for e in eps:
            sp = set(e.get("supported_parameters") or [])
            if e.get("status", 0) != 0 or (e.get("uptime_last_30m") or 0) < 99 or (e.get("context_length") or 0) < MIN_CONTEXT:
                continue
            if "seed" not in sp or (wants_temp and "temperature" not in sp):
                continue
            # avoid heavily quantized weights (quality) and "flex" tiers (queued / throttled)
            if (e.get("quantization") or "").lower() in ("fp4", "int4", "fp6") or "flex" in (e.get("tag") or ""):
                continue
            pi, po = float(e["pricing"]["prompt"]) * 1e6, float(e["pricing"]["completion"]) * 1e6
            ok.append((450e3 * pi + 70e3 * po, pi, po, e, sp))
        if not ok:
            print(f"!! {mid}: no endpoint with seed{' + temperature' if wants_temp else ''}; skipped")
            continue
        _, pi, po, e, sp = min(ok, key=lambda r: r[0])
        registry[mid] = {
            "provider": e["tag"],
            "provider_name": e["provider_name"],
            "quantization": e.get("quantization"),
            "price_input_per_m": round(pi, 6),
            "price_output_per_m": round(po, 6),
            "supports_temperature": "temperature" in sp,
            "supports_seed": "seed" in sp,
            "supports_reasoning": "reasoning" in sp or "reasoning" in model_params,
            "context_length": e.get("context_length"),
            "snapshot": datetime.date.today().isoformat(),
        }
        r = registry[mid]
        print(f"{mid:42s} -> {r['provider']:22s} {r['quantization'] or '-':6s} in={pi:.3f} out={po:.3f} "
              f"temp={r['supports_temperature']} seed={r['supports_seed']} reasoning={r['supports_reasoning']}")
    out.write_text("# Generated by scripts/openrouter_models.py; pinned provider + prices (USD per million tokens).\n"
                   + yaml.safe_dump(registry, sort_keys=True))
    print(f"wrote {out} ({len(registry)} models)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
