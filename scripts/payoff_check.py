"""Payoffs of unilateral strategies in market v1, against all-cost play (no LLM; methods §3.4).

    python scripts/payoff_check.py [--seeds 400] [--out results/core/payoff_check.md]

One firm deviates; both rival firms bid cost with d = 0. Strategies for the deviating firm:
- push: its trading desk deviates 25 MW in the direction of the (unpushed) system imbalance. This uses perfect
  foresight of the direction, so it is an upper bound on what a forecasting desk can achieve;
- bid: its balancing desk marks up the block (x1.3 = 30% markup, the label threshold; x2 = up 2x cost and down
  at 0; cap = up at the price cap and down at the floor), with no deviation;
- both: push and bid together (intra-firm self-dealing).
Noise comes from the same generator as the simulation (scripts share `make_streams`), clearing and settlement from
`desks.market`.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

from desks.config import MarketParams
from desks.market import clear, make_units, settle
from desks.simulation import make_streams

PUSH = 25.0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=400)
    ap.add_argument("--out", default="results/core/payoff_check.md")
    args = ap.parse_args()
    m = MarketParams()
    units = make_units(m, 3)
    high = {"x1.3": (1.3 * units.c_up, 0.7 * units.c_down), "x2": (2 * units.c_up, 0 * units.c_down),
            "cap": (np.full(3, m.price_cap), np.full(3, m.price_floor))}
    strategies = [("push", None)] + [(s, h) for s in ("bid", "both") for h in high]
    res: dict[tuple, list[float]] = {}
    for seed in range(args.seeds):
        e, r, tie, _, _ = make_streams(seed, m.T, 3, m.sigma_f, m.sigma_r, m.rho)
        for t in range(m.T):
            S0 = float(e[t].sum() + r[t])
            cl0 = clear(S0, units.c_up, units.c_down, units.mw, np.ones(3, bool), tie[t], m)
            st0 = settle(e[t], r[t], cl0, units.c_up, units.c_down, m.lam)
            for i in range(3):
                for strat, h in strategies:
                    u, v, x = units.c_up.copy(), units.c_down.copy(), e[t].copy()
                    if strat in ("bid", "both"):
                        u[i], v[i] = high[h][0][i], high[h][1][i]
                    if strat in ("push", "both"):
                        x[i] += np.sign(S0) * PUSH
                    cl = clear(float(x.sum() + r[t]), u, v, units.mw, np.ones(3, bool), tie[t], m)
                    st = settle(x, r[t], cl, units.c_up, units.c_down, m.lam)
                    res.setdefault((strat, h, "ABC"[i]), []).append(st.brp[i] + st.bsp[i] - st0.brp[i] - st0.bsp[i])
    lines = [f"# Unilateral strategies against all-cost play ({args.seeds} seeds x {m.T} periods)", "",
             "Generated by `scripts/payoff_check.py`. Change in the deviating firm's profit; rivals bid cost, d = 0.", "",
             "| strategy | bid level | firm | € per run (mean) | share of periods with a gain |", "|---|---|---|---|---|"]
    for (strat, h, f), v in res.items():
        v = np.asarray(v)
        lines.append(f"| {strat} | {h or '-'} | {f} | {m.T * v.mean():,.0f} | {np.mean(v > 0):.3f} |")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
